#!/bin/bash
# articles/images/generate.sh
#
# 本書のプレースホルダ図を ImageMagick で生成する。
# 図の差し替えはこのスクリプトを書き換えて再実行、またはこの下の
# PNG を .re ファイルと同じ名前で自力に置き換える。
#
# 使い方: ./generate.sh

set -euo pipefail

cd "$(dirname "$0")"

FONT=".Hiragino-Kaku-Gothic-Interface-W3"
FONTB=".Hiragino-Kaku-Gothic-Interface-W6"

if [[ "$(uname)" != "Darwin" ]]; then
  echo "このスクリプトは macOS (Hiragino フォント) を想定しています。" >&2
  echo "Linux では FONT=NotoSansCJK-Regular などに書き換えてください。" >&2
  exit 1
fi

# ---------------------------------------------------------------- helpers

d=()

rect() { # x1 y1 x2 y2
  d+=(-fill white -stroke black -strokewidth 2 -draw "rectangle $1,$2 $3,$4")
}

tx() { # text size x y
  d+=(-fill black -stroke none -pointsize "$2" -draw "text $3,$4 '$1'")
}

txg() { # text size x y （グレーの注釈）
  d+=(-fill '#555555' -stroke none -pointsize "$2" -draw "text $3,$4 '$1'")
}

ln() { # x1 y1 x2 y2
  d+=(-stroke '#333333' -strokewidth 2 -fill none -draw "line $1,$2 $3,$4")
}

arrowdown() { # x y1 y2
  ln "$1" "$2" "$1" "$(($3-12))"
  d+=(-fill '#333333' -stroke none -draw "polygon $(($1-7)),$(($3-12)) $(($1+7)),$(($3-12)) $1,$3")
}

arrowup() { # x y1 y2 （y1: 下端、y2: 上端）
  ln "$1" "$2" "$1" "$(($3+12))"
  d+=(-fill '#333333' -stroke none -draw "polygon $(($1-7)),$(($3+12)) $(($1+7)),$(($3+12)) $1,$3")
}

arrowright() { # x1 x2 y
  ln "$1" "$3" "$(($2-12))" "$3"
  d+=(-fill '#333333' -stroke none -draw "polygon $(($2-12)),$(($3-7)) $(($2-12)),$(($3+7)) $2,$3")
}

arrowleft() { # x1 x2 y
  ln "$1" "$3" "$(($2+12))" "$3"
  d+=(-fill '#333333' -stroke none -draw "polygon $(($2+12)),$(($3-7)) $(($2+12)),$(($3+7)) $2,$3")
}

emit() { # 出力ファイル名 幅 高さ
  magick -size "$2x$3" xc:white -font "$FONT" "${d[@]}" "$1"
  echo "wrote $1 ($2x$3)"
  d=()
}

